"""Gestion de la configuration"""

import os
import yaml
from pathlib import Path
from dataclasses import dataclass
from typing import Optional, List


@dataclass
class TrackerConfig:
    url: str
    api_key: str
    tracker_urls: List[str]


@dataclass
class QuiConfig:
    api_url: str
    api_key: str
    instance_id: int
    content_path_prefix: str = ""
    content_path_replacement: str = ""
    upload_tag: str = "Auto_UP_Draupnirr"

@dataclass
class TmdbConfig:
    api_key: str = ""  # Optionnel : sert uniquement à lire les genres TMDB
    language: str = "fr-FR"


@dataclass
class CategoriesConfig:
    """Slugs Draupnirr par type détecté (liste exacte : GET /api/categories)"""
    movie: str = "films-film"
    tv: str = "series-serie-tv"
    documentary: str = "films-film"
    concert: str = "films-film"
    animated_movie: str = "films-film"
    animated_tv: str = "series-serie-tv"


@dataclass
class OptionsConfig:
    page_size: int = 10
    nfo_signature: str = "NFO automatically Generated by: Draupnirr-AutoUploader"
    temp_dir: str = "/tmp/draupnirr-uploader"
    skip_no_team_prompt: bool = False
    auto_next_page: bool = False
    only_missing: str = ""  # "" (tout afficher), "work" (l'œuvre manque sur Draupnirr) ou "slot" (le slot visé est libre)

@dataclass
class Config:
    tracker: TrackerConfig
    qui: QuiConfig
    tmdb: TmdbConfig
    categories: CategoriesConfig
    options: OptionsConfig


def load_config(config_path: Optional[str] = None) -> Config:
    """Charge la configuration depuis un fichier YAML"""

    if config_path is None:
        search_paths = [
            Path.cwd() / "config.yaml",
            Path.home() / ".config" / "src" / "config.yaml",
            Path(__file__).parent.parent / "config.yaml",
        ]

        for path in search_paths:
            if path.exists():
                config_path = str(path)
                break
        else:
            raise FileNotFoundError(
                "Fichier de configuration non trouvé. "
                "Créez config.yaml à partir de config.example.yaml"
            )

    with open(config_path, 'r', encoding='utf-8') as f:
        data = yaml.safe_load(f)

    # Check et créer la configuration
    tracker_data = data['tracker']
    if not tracker_data.get('api_key'):
        raise ValueError(
            "tracker.api_key manquant : passkey ou jeton API Draupnirr (drp_...). "
            "bearer_token et api_url ne sont plus utilisés"
        )
    if not tracker_data.get('url'):
        raise ValueError("tracker.url manquant : adresse du site Draupnirr (ex: https://draupnirr.example)")

    # URL racine du site : les routes de l'API commencent toutes par /api/
    url = tracker_data['url'].rstrip('/')
    if url.endswith('/api'):
        url = url[:-len('/api')]

    tracker = TrackerConfig(
        url=url,
        api_key=tracker_data['api_key'],
        tracker_urls=tracker_data.get('tracker_urls', [])
    )

    # Extraire les valeurs optionnelles (les défauts sont dans les dataclasses)
    qui_data = data['qui']
    qui_kwargs = {
        'api_url': qui_data['api_url'],
        'api_key': qui_data['api_key'],
    }
    if 'instance_id' in qui_data:
        qui_kwargs['instance_id'] = qui_data['instance_id']
    if 'content_path_prefix' in qui_data:
        qui_kwargs['content_path_prefix'] = qui_data['content_path_prefix']
    if 'content_path_replacement' in qui_data:
        qui_kwargs['content_path_replacement'] = qui_data['content_path_replacement']
    if 'upload_tag' in qui_data:
        qui_kwargs['upload_tag'] = qui_data['upload_tag']
    qui = QuiConfig(**qui_kwargs)

    tmdb_data = data.get('tmdb') or {}
    tmdb_kwargs = {}
    if tmdb_data.get('api_key'):
        tmdb_kwargs['api_key'] = tmdb_data['api_key']
    if 'language' in tmdb_data:
        tmdb_kwargs['language'] = tmdb_data['language']
    tmdb = TmdbConfig(**tmdb_kwargs)

    categories_data = data.get('categories') or {}
    categories_kwargs = {}
    for key in CategoriesConfig.__dataclass_fields__:
        if categories_data.get(key):
            categories_kwargs[key] = categories_data[key]
    categories = CategoriesConfig(**categories_kwargs)

    options_data = data.get('options', {})
    options_kwargs = {}
    if 'page_size' in options_data:
        options_kwargs['page_size'] = options_data['page_size']
    if 'nfo_signature' in options_data:
        options_kwargs['nfo_signature'] = options_data['nfo_signature']
    if 'temp_dir' in options_data:
        options_kwargs['temp_dir'] = options_data['temp_dir']
    if 'skip_no_team_prompt' in options_data:
        options_kwargs['skip_no_team_prompt'] = options_data['skip_no_team_prompt']
    if 'auto_next_page' in options_data:
        options_kwargs['auto_next_page'] = options_data['auto_next_page']
    if 'skip_existing' in options_data:
        raise ValueError("options.skip_existing a été renommée only_missing (mêmes valeurs)")
    if 'only_missing' in options_data:
        only_missing = options_data['only_missing'] or ""
        if only_missing not in ("", "work", "slot"):
            raise ValueError('options.only_missing : false, "work" ou "slot"')
        options_kwargs['only_missing'] = only_missing
    options = OptionsConfig(**options_kwargs)

    os.makedirs(options.temp_dir, exist_ok=True)

    return Config(tracker=tracker, qui=qui, tmdb=tmdb, categories=categories, options=options)
